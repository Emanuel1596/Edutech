BEGIN;

CREATE OR REPLACE VIEW vw_orden_resumen AS
SELECT
  o.id_orden,
  o.numero_orden,
  u.id_usuario,
  u.nombre || ' ' || u.apellido_paterno AS alumno,
  eo.nombre_estado_orden,
  m.codigo_moneda,
  o.total,
  o.fecha_creacion,
  COUNT(od.id_orden_detalle) AS total_cursos
FROM orden o
JOIN usuario u ON u.id_usuario = o.id_usuario
JOIN estado_orden eo ON eo.id_estado_orden = o.id_estado_orden
JOIN moneda m ON m.id_moneda = o.id_moneda
LEFT JOIN orden_detalle od ON od.id_orden = o.id_orden
GROUP BY
  o.id_orden,
  o.numero_orden,
  u.id_usuario,
  u.nombre,
  u.apellido_paterno,
  eo.nombre_estado_orden,
  m.codigo_moneda,
  o.total,
  o.fecha_creacion;

CREATE OR REPLACE VIEW vw_inscripcion_detalle AS
SELECT
  i.id_inscripcion,
  i.fecha_inscripcion,
  i.fecha_finalizacion,
  ei.nombre_estado_inscripcion,
  o.id_orden,
  o.numero_orden,
  alumno.id_usuario AS id_alumno,
  alumno.nombre || ' ' || alumno.apellido_paterno AS alumno,
  c.id_curso,
  c.titulo AS curso,
  instructor.id_usuario AS id_instructor,
  instructor.nombre || ' ' || instructor.apellido_paterno AS instructor
FROM inscripcion i
JOIN estado_inscripcion ei ON ei.id_estado_inscripcion = i.id_estado_inscripcion
JOIN orden_detalle od ON od.id_orden_detalle = i.id_orden_detalle
JOIN orden o ON o.id_orden = od.id_orden
JOIN usuario alumno ON alumno.id_usuario = o.id_usuario
JOIN curso c ON c.id_curso = od.id_curso
JOIN usuario instructor ON instructor.id_usuario = c.id_usuario;

COMMIT;

